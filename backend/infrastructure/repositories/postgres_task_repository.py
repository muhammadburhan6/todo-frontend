import os
from pathlib import Path

import psycopg
from dotenv import load_dotenv

from domain.entities.task import Task


PROJECT_ROOT = Path(__file__).resolve().parents[3]
load_dotenv(PROJECT_ROOT / ".env")


def get_postgres_connection():
    database_url = os.getenv("DATABASE_URL") or os.getenv("POSTGRESQL_URI")
    if not database_url:
        raise RuntimeError(
            "DATABASE_URL (or POSTGRESQL_URI) is missing from .env. "
            "Set it to your PostgreSQL connection URI."
        )
    if database_url.strip().upper() in {
        "YAHAN_SUPABASE_KI_CONNECTION_STRING",
        "YOUR_SUPABASE_CONNECTION_STRING",
        "YOUR_DATABASE_URL",
    }:
        raise RuntimeError(
            "DATABASE_URL in .env is still a placeholder. Replace it with your "
            "Supabase PostgreSQL URI (Project Settings > Database > Connection string), "
            "or set DATABASE_MODE=memory to run temporarily without a database."
        )
    connection = psycopg.connect(database_url)
    with connection.cursor() as cursor:
        cursor.execute("""
            CREATE TABLE IF NOT EXISTS users (
                id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                email TEXT NOT NULL UNIQUE,
                password_hash TEXT NOT NULL,
                created_at TIMESTAMPTZ NOT NULL
            )
        """)
        cursor.execute("""
            CREATE TABLE IF NOT EXISTS tasks (
                id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                title TEXT NOT NULL,
                completed BOOLEAN NOT NULL DEFAULT FALSE,
                user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE
            )
        """)
        cursor.execute("CREATE INDEX IF NOT EXISTS tasks_user_id_idx ON tasks(user_id)")
    connection.commit()
    return connection


class PostgresTaskRepository:
    def __init__(self, connection=None):
        self.connection = connection or get_postgres_connection()

    @staticmethod
    def _task(row):
        return Task(task_id=row[0], title=row[1], completed=row[2], user_id=row[3])

    def create(self, task):
        if task.user_id is None:
            raise ValueError("Task must be associated with a valid user_id")
        with self.connection.cursor() as cursor:
            cursor.execute(
                "INSERT INTO tasks (title, completed, user_id) VALUES (%s, %s, %s) RETURNING id",
                (task.title, task.completed, int(task.user_id)),
            )
            task.id = cursor.fetchone()[0]
        self.connection.commit()
        return task

    def get_all(self, user_id=None):
        if user_id is None:
            return []
        with self.connection.cursor() as cursor:
            cursor.execute("SELECT id, title, completed, user_id FROM tasks WHERE user_id = %s ORDER BY id", (int(user_id),))
            return [self._task(row) for row in cursor.fetchall()]

    def get_by_id(self, task_id, user_id=None):
        if user_id is None:
            return None
        try:
            task_id, user_id = int(task_id), int(user_id)
        except (TypeError, ValueError):
            return None
        with self.connection.cursor() as cursor:
            cursor.execute("SELECT id, title, completed, user_id FROM tasks WHERE id = %s AND user_id = %s", (task_id, user_id))
            row = cursor.fetchone()
        return self._task(row) if row else None

    def update(self, task_id, task, user_id=None):
        if user_id is None:
            return None
        try:
            task_id, user_id = int(task_id), int(user_id)
        except (TypeError, ValueError):
            return None
        with self.connection.cursor() as cursor:
            cursor.execute("UPDATE tasks SET title = %s, completed = %s WHERE id = %s AND user_id = %s RETURNING id", (task.title, task.completed, task_id, user_id))
            row = cursor.fetchone()
        if not row:
            self.connection.rollback()
            return None
        self.connection.commit()
        task.id, task.user_id = row[0], user_id
        return task

    def delete(self, task_id, user_id=None):
        if user_id is None:
            return False
        try:
            task_id, user_id = int(task_id), int(user_id)
        except (TypeError, ValueError):
            return False
        with self.connection.cursor() as cursor:
            cursor.execute("DELETE FROM tasks WHERE id = %s AND user_id = %s", (task_id, user_id))
            deleted = cursor.rowcount > 0
        self.connection.commit()
        return deleted
